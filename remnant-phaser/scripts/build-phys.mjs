// Builds the physics core (physics/remnant_phys.c) into WebAssembly with clang's wasm32 target and wasm-ld, then
// writes src/game/physWasm.ts, the module as base64, so the game carries it with no fetch (and so offline).
// Run after changing the C: `node scripts/build-phys.mjs`. Both outputs are committed, so the game's own build
// does not need clang.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('..', import.meta.url).pathname;
const src = root + 'physics/remnant_phys.c', out = root + 'physics/remnant_phys.wasm';
execFileSync('clang', [
  '--target=wasm32', '-O3', '-nostdlib', '-mnontrapping-fptoint', '-mbulk-memory',
  '-Wl,--no-entry', '-Wl,--strip-all', '-Wl,--export-dynamic', '-Wl,-z,stack-size=8192',
  '-o', out, src,
], { stdio: 'inherit' });
const bytes = readFileSync(out);
const sha = createHash('sha256').update(readFileSync(src)).digest('hex').slice(0, 12);
writeFileSync(root + 'src/game/physWasm.ts',
  `// Generated by scripts/build-phys.mjs from physics/remnant_phys.c (source ${sha}). Do not edit.\n` +
  `export const PHYS_WASM = '${bytes.toString('base64')}';\n` +
  `export const PHYS_SOURCE = '${sha}';\n`);
console.log(`physics: ${bytes.length} bytes of WebAssembly from ${sha}`);
